function assertCatalog() {
  const slugs = new Set<string>();
  const userById = new Map(users.map((user) => [user.id, user]));

  if (listings.length < 24) {
    throw new Error(`Expected at least 24 listings, found ${listings.length}`);
  }

  for (const listing of listings) {
    const slugKey = `${listing.country}:${listing.slug}`;
    if (slugs.has(slugKey)) throw new Error(`Duplicate slug ${slugKey}`);
    slugs.add(slugKey);

    const seller = userById.get(listing.sellerId);
    if (!seller) throw new Error(`Missing seller for ${listing.id}`);
    if (seller.country !== listing.country) {
      throw new Error(`Seller country mismatch on ${listing.id}`);
    }
    if (listing.currency !== countries[listing.country].currency) {
      throw new Error(`Currency mismatch on ${listing.id}`);
    }
    if (!countries[listing.country].cities.includes(listing.city)) {
      throw new Error(`Unknown city on ${listing.id}`);
    }
    if (seller.city !== listing.city && !countries[listing.country].cities.includes(seller.city)) {
      throw new Error(`Seller city mismatch on ${seller.id}`);
    }
  }
}

assertCatalog();
